'use strict';
/* Generate providers/krmizi-archive.js from providers/krmizi.js.
 * The two entries never carry duplicated logic: the archive build is the fast
 * file with SOURCE_PROFILE flipped and the header rewritten. Run this after any
 * edit to krmizi.js (and keep both files in the same release). */
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');

const FAST_LINE = 'var SOURCE_PROFILE = "fast";';
const ARCHIVE_LINE = 'var SOURCE_PROFILE = "archive";';
const FAST_TITLE = ' * Krmizi / Qrmzi provider for Nuvio';
const ARCHIVE_TITLE = ' * Krmizi / Qrmzi archive provider for Nuvio';
const FAST_PROFILE_LINE = ' * Profile: fast';
const ARCHIVE_PROFILE_LINE = ' * Profile: archive\n * Generated by scripts/build-profiles.js from providers/krmizi.js; do not edit by hand.';

function replaceOnce(text, from, to, label) {
  const parts = text.split(from);
  if (parts.length !== 2) {
    throw Error(label + ': expected exactly one match, found ' + (parts.length - 1));
  }
  return parts[0] + to + parts[1];
}

function generate(fastSource) {
  let source = replaceOnce(fastSource, FAST_TITLE, ARCHIVE_TITLE, 'header title');
  source = replaceOnce(source, FAST_PROFILE_LINE, ARCHIVE_PROFILE_LINE, 'header profile');
  return replaceOnce(source, FAST_LINE, ARCHIVE_LINE, 'SOURCE_PROFILE');
}

function main() {
  const sourcePath = path.join(root, 'providers/krmizi.js');
  const outputPath = path.join(root, 'providers/krmizi-archive.js');
  fs.writeFileSync(outputPath, generate(fs.readFileSync(sourcePath, 'utf8')));
  console.log('build-profiles: ' + path.relative(root, outputPath) + ' generated from ' + path.relative(root, sourcePath));
}

module.exports = { generate };

if (require.main === module) main();
